def _mark(name: str, args: dict[str, Any]) -> Mark:
    args = dict(args)
    data = args.pop("data")
    options = args.pop("options")
    enc = {k: v for k, v in args.items() if v is not UNSET}
    enc.update(options)
    return Mark(name, data=data, enc=enc or None)


